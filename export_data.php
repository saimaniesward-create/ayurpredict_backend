// 3. Fetch Daily Check-ins (ALL columns)
$checkin_data = [];
$stmt = $conn->prepare("SELECT 
    DATE(created_at) as date,
    sleep_hours, sleep_quality, stress_level,
    morning_energy, evening_energy,
    body_dryness, body_heat, body_heaviness, cold_body,
    sweet_craving, spicy_craving,
    elimination, hydration_level, mood,
    physical_activity, digestion, appetite
    FROM daily_checkins WHERE user_id = ? ORDER BY created_at DESC");
$stmt->bind_param("i", $user_id);
$stmt->execute();
$res = $stmt->get_result();
while ($row = $res->fetch_assoc()) {
    $checkin_data[] = $row;
}
$stmt->close();


// 4. Generate PDF
class PDF extends FPDF
{
    function Header()
    {
        $this->SetFont('Arial','B',15);
        $this->Cell(0,10,'AyurPredict - User Data Export',0,1,'C');
        $this->Ln(5);
    }

    function Footer()
    {
        $this->SetY(-15);
        $this->SetFont('Arial','I',8);
        $this->Cell(0,10,'Page '.$this->PageNo().' - Generated by AyurPredict',0,0,'C');
    }
}

$pdf = new PDF('L', 'mm', 'A4'); // Landscape
