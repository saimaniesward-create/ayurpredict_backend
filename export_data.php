$pdf->Cell(0,10,'Dosha History',0,1);
$pdf->SetFont('Arial','B',10);
$pdf->SetFillColor(200,220,255);
$pdf->Cell(40,8,'Date',1,0,'C',true);
$pdf->Cell(30,8,'Vata',1,0,'C',true);
$pdf->Cell(30,8,'Pitta',1,0,'C',true);
