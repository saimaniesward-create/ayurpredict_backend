    $pdf->Cell(30,8,$row['vata_score'],1);
    $pdf->Cell(30,8,$row['pitta_score'],1);
    $pdf->Cell(30,8,$row['kapha_score'],1,1);
}
$pdf->Ln(10);

// Daily Check-ins Table
$pdf->SetFont('Arial','B',14);
$pdf->Cell(0,10,'Daily Check-ins',0,1);

// Detailed Headers (Abbreviated to fit)
$headers = ['Date', 'Sleep', 'Qlty', 'Strss', 'M.En', 'E.En', 'Dry', 'Hot', 'Hvy', 'Cld', 'Swt', 'Spc', 'Elim', 'H2O', 'Mood', 'Actv', 'Digs', 'Appt'];
$widths =  [25,     12,      15,     15,      12,     12,     10,    10,    10,    10,    10,    10,    15,     12,    15,     15,     15,     15]; // Total ~240mm (A4 L is 297mm)

$pdf->SetFont('Arial','B',8);
$pdf->SetFillColor(200,255,200);
for($i=0; $i<count($headers); $i++) {
    $pdf->Cell($widths[$i], 8, $headers[$i], 1, 0, 'C', true);
}
$pdf->Ln();

$pdf->SetFont('Arial','',8);
foreach($checkin_data as $row) {
    $data = [
        $row['date'],
        $row['sleep_hours'], $row['sleep_quality'], $row['stress_level'],
        $row['morning_energy'], $row['evening_energy'],
        $row['body_dryness']?'Y':'N', $row['body_heat']?'Y':'N', $row['body_heaviness']?'Y':'N', $row['cold_body']?'Y':'N',
        $row['sweet_craving']?'Y':'N', $row['spicy_craving']?'Y':'N',
        $row['elimination'], $row['hydration_level'], $row['mood'],
        $row['physical_activity'], $row['digestion'], $row['appetite']
    ];
    
    // Check page break
    if($pdf->GetY() > 180) {
        $pdf->AddPage();
        // Re-print header
        $pdf->SetFont('Arial','B',8);
        for($i=0; $i<count($headers); $i++) {
            $pdf->Cell($widths[$i], 8, $headers[$i], 1, 0, 'C', true);
        }
        $pdf->Ln();
        $pdf->SetFont('Arial','',8);
    }

    for($i=0; $i<count($data); $i++) {
        // Truncate text if too long
        $text = $data[$i];
        if(strlen($text) > 8 && $i > 0) $text = substr($text, 0, 7) . '.'; 
        $pdf->Cell($widths[$i], 8, $text, 1, 0, 'C');
    }
    $pdf->Ln();
}

$pdf_content = $pdf->Output('S');

